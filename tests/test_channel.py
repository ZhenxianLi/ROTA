def test_level_follows_a_speed_ramp():
    # 20 -> 160 km/h in 10 s, 18 dB per doubling (a v**6 power law).
    v = np.linspace(20.0, 160.0, N)
    kw = dict(NOISE, level_slope_db_per_doubling=18.0)
    y, _ = speed_noise(FS, N, v, seed=5, **kw)
    block = int(FS)
    measured = _db(np.mean(y.reshape(-1, block) ** 2, axis=1))
    # expected mean power of each block: the average of the instantaneous law
    law = 10 ** ((-20.0 + 18.0 * np.log2(v / 80.0)) / 10)
    expected = _db(np.mean(law.reshape(-1, block), axis=1))
    assert np.max(np.abs(measured - expected)) < 0.6  # measured within 0.3 dB (1 s blocks)
    assert measured[-1] - measured[0] > 30.0


