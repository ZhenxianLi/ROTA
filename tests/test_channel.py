def test_apply_ir_equals_direct_convolution_truncated_to_the_input_length():
    rng = np.random.default_rng(2)
    x = rng.standard_normal(500)
    h = rng.standard_normal(80)
    y = apply_ir(x, h)
    assert y.shape == x.shape
    assert y == pytest.approx(np.convolve(x, h)[:500], rel=1e-10, abs=1e-12)
    # an IR longer than the signal
    long = rng.standard_normal(900)
    assert apply_ir(x, long) == pytest.approx(np.convolve(x, long)[:500], rel=1e-10, abs=1e-12)
    # a unit impulse leaves the signal alone, a delayed one delays it
    delta = np.zeros(10)
    delta[0] = 1.0
    assert apply_ir(x, delta) == pytest.approx(x, abs=1e-12)
    delta[3] = 1.0
    delta[0] = 0.0
    shifted = apply_ir(x, delta)
    assert shifted[3:] == pytest.approx(x[:-3], abs=1e-12)
    assert np.all(np.abs(shifted[:3]) < 1e-12)
    # linearity
    h2 = rng.standard_normal(80)
    assert apply_ir(x, 2.0 * h - 0.5 * h2) == pytest.approx(
        2.0 * apply_ir(x, h) - 0.5 * apply_ir(x, h2), rel=1e-10, abs=1e-11
    )


def test_apply_ir_channel_handling():
    rng = np.random.default_rng(3)
    n, m = 400, 60
    x1, h1 = rng.standard_normal(n), rng.standard_normal(m)
    x3, h3 = rng.standard_normal((n, 3)), rng.standard_normal((m, 3))
    # mono source to three receivers
    y = apply_ir(x1, h3)
    assert y.shape == (n, 3)
    for c in range(3):
        assert y[:, c] == pytest.approx(np.convolve(x1, h3[:, c])[:n], abs=1e-10)
    # one IR for every signal channel
    y = apply_ir(x3, h1)
    assert y.shape == (n, 3)
    assert y[:, 2] == pytest.approx(np.convolve(x3[:, 2], h1)[:n], abs=1e-10)
    # channel by channel
    y = apply_ir(x3, h3)
    assert y[:, 1] == pytest.approx(np.convolve(x3[:, 1], h3[:, 1])[:n], abs=1e-10)
    # shapes of single-column inputs are kept 2-D
    assert apply_ir(x1[:, None], h1).shape == (n, 1)
