def test_analog_response_closed_forms():
    g, zeta, f0 = 2.0, 0.05, 200.0
    modes = [dict(freq=f0, zeta=zeta, gain=g)]
    # at the resonance: g / (2 zeta) with a phase of -90 degrees
    assert modal_response(f0, modes) == pytest.approx(-1j * g / (2 * zeta), rel=1e-12)
    assert modal_response(0.0, modes) == pytest.approx(g, rel=1e-12)  # static gain
    assert modal_response(1e5, modes).real == pytest.approx(-g * (f0 / 1e5) ** 2, rel=1e-3)
    # half-power points at f0 (1 +- zeta) for a light damping
    light = [dict(freq=f0, zeta=0.005, gain=g)]
    for f in (f0 * (1 - 0.005), f0 * (1 + 0.005)):
        assert abs(modal_response(f, light)) == pytest.approx(g / 0.01 / np.sqrt(2), rel=1e-2)
    # Q and damping ratio are the same parameter
    assert modal_response(150.0, [dict(freq=f0, q=10.0, gain=g)]) == pytest.approx(
        modal_response(150.0, [dict(freq=f0, zeta=0.05, gain=g)]), rel=1e-12
    )
    # the response of a sum of modes is the sum of the responses; shape is kept
    f = np.linspace(10.0, 2000.0, 12).reshape(3, 4)
    both = modal_response(f, MODES)
    assert both.shape == f.shape
    assert both == pytest.approx(
        modal_response(f, MODES[:1]) + modal_response(f, MODES[1:]), rel=1e-12
    )


def test_digital_response_follows_the_analog_ideal_well_below_nyquist():
    mode = [dict(freq=300.0, zeta=0.02)]
    f = np.linspace(0.0, 800.0, 161)
    ha, hd = modal_response(f, mode), modal_response(f, mode, FS)
    # Impulse invariance aliases the analog response (Poisson sum). At 0 Hz the
    # aliases of all orders add up to 1 - H_d(0) = (pi**2 / 3) (f0 / fs)**2 = 1.16e-3
    # of the static gain; the error is nearly constant over the band.
    assert 1.0 - hd[0].real == pytest.approx(np.pi**2 / 3 * (300.0 / FS) ** 2, rel=0.01)
    assert np.max(np.abs(hd - ha)) < 1.3e-3
    assert abs(modal_response(300.0, mode, FS)) == pytest.approx(25.0, rel=2e-3)
    assert np.angle(modal_response(300.0, mode, FS)) == pytest.approx(-np.pi / 2, abs=2e-3)


@pytest.mark.parametrize("f", [120.0, 300.0, 305.0, 700.0, 1090.0, 1100.0, 3000.0])
def test_sine_steady_state_matches_the_digital_response(f):
    n = int(2.5 * FS)
    t = np.arange(n) / FS
    x = 1.5 * np.cos(TWO_PI * f * t + 0.4)
    y, _ = modal_path(x, FS, MODES)
    last = slice(n - 8000, n)  # 2 s after the start: all transients are gone
    z = _fit_tone(y[last], f, t[last])
    expected = 1.5 * np.exp(0.4j) * modal_response(f, MODES, FS)
    assert abs(z / expected - 1) < 1e-8  # amplitude and phase


def test_impulse_response_is_the_sampled_analog_impulse_response():
    fs = 8000.0
    modes = [dict(freq=400.0, zeta=0.03, gain=1.2), dict(freq=900.0, zeta=0.01, gain=-0.7)]
    x = np.zeros(4000)
    x[0] = 1.0
    y, _ = modal_path(x, fs, modes)
    t = np.arange(x.size) / fs
    expected = np.zeros_like(t)
    for m in modes:
        w0 = TWO_PI * m["freq"]
        wd = w0 * np.sqrt(1 - m["zeta"] ** 2)
        expected += m["gain"] * w0**2 / wd * np.exp(-m["zeta"] * w0 * t) * np.sin(wd * t) / fs
    assert np.max(np.abs(y - expected)) < 1e-12 * np.max(np.abs(expected))


def test_ring_down_time_constant_is_one_over_zeta_omega():
    fs, f0, zeta = 8000.0, 400.0, 0.01
    tau = 1.0 / (zeta * TWO_PI * f0)  # 39.8 ms
    t = np.arange(int(1.0 * fs)) / fs
    n_on = int(0.4 * fs)
    x = np.where(np.arange(t.size) < n_on, np.cos(TWO_PI * f0 * t), 0.0)  # switched off at 0.4 s
    y, cfg = modal_path(x, fs, [dict(freq=f0, zeta=zeta)])
    assert cfg["modes"][0]["decay_time"] == pytest.approx(tau, rel=1e-12)
    env = np.abs(signal.hilbert(y))
    assert env[n_on] == pytest.approx(1.0 / (2 * zeta), rel=0.02)  # steady state before the cut
    seg = slice(n_on + int(0.3 * tau * fs), n_on + int(5 * tau * fs))
    slope = np.polyfit(t[seg], np.log(env[seg]), 1)[0]
    assert -1.0 / slope == pytest.approx(tau, rel=5e-3)
    # after the cut the response rings at the damped frequency
    ring = y[n_on + int(0.5 * tau * fs): n_on + int(4 * tau * fs)]
    spec = np.abs(np.fft.rfft(ring * np.hanning(ring.size), 1 << 16))
    f_peak = np.fft.rfftfreq(1 << 16, 1 / fs)[np.argmax(spec)]
    assert f_peak == pytest.approx(f0 * np.sqrt(1 - zeta**2), abs=1.0)


def _sweep_through_mode(rate, f1, f2, fs, modes):
    t = np.arange(int((f2 - f1) / rate * fs)) / fs
    phase = TWO_PI * (f1 * t + 0.5 * rate * t**2)
    y, _ = modal_path(np.cos(phase), fs, modes)
    return t, phase, f1 + rate * t, y


def test_slow_sweep_is_quasi_static_and_fast_sweep_shows_the_ring_down():
    # Mode at 100 Hz, zeta 0.02: half-power bandwidth 4 Hz, ring-down 80 ms.
    fs, f0, zeta = 2000.0, 100.0, 0.02
    modes = [dict(freq=f0, zeta=zeta)]
    peak = 1.0 / (2 * zeta)

    # 1 Hz/s: the sweep needs 4 s to cross the bandwidth (50 ring-down times)
    _, phase, f_inst, y = _sweep_through_mode(1.0, 80.0, 120.0, fs, modes)
    env = np.abs(signal.hilbert(y))
    assert env.max() == pytest.approx(peak, rel=0.02)  # |H(f0)|
    assert f_inst[np.argmax(env)] == pytest.approx(f0, abs=1.0)
    h = modal_response(f_inst, modes)  # quasi-static prediction
    sel = slice(2000, -2000)
    assert np.max(np.abs(y - np.abs(h) * np.cos(phase + np.angle(h)))[sel]) < 0.1 * peak
    # the phase rotates by almost 180 degrees across the resonance
    rel = np.angle(signal.hilbert(y) * np.conj(signal.hilbert(np.cos(phase))))
    lo, hi = np.argmin(np.abs(f_inst - 93.0)), np.argmin(np.abs(f_inst - 107.0))
    assert abs(rel[lo] - np.angle(modal_response(93.0, modes))) < 0.1
    assert abs(rel[hi] - np.angle(modal_response(107.0, modes))) < 0.1
    assert abs(rel[hi] - rel[lo]) > 0.8 * np.pi

    # 400 Hz/s: the mode is crossed in a small fraction of the ring-down time
    _, phase, f_inst, y = _sweep_through_mode(400.0, 40.0, 160.0, fs, modes)
    env = np.abs(signal.hilbert(y))
    assert env.max() < 0.6 * peak  # the mode cannot build up
    assert f_inst[np.argmax(env)] > f0 + 8.0  # and answers late: it is still ringing
    h = modal_response(f_inst, modes)
    assert np.max(np.abs(y - np.abs(h) * np.cos(phase + np.angle(h)))) > 0.3 * peak


def test_run_up_order_crossing_a_mode_follows_the_synth_truth():
    # Order 2 of a slow linear run-up passes a mode at 150 Hz. synth_runup
    # stores the exact amplitude, phase and frequency of the order; for a
    # sweep much slower than the ring-down the filtered order is
    # A |H(f)| cos(Phi + arg H(f)) (quasi-static), which the filter reproduces.
    fs = 4000.0
    rpm = np.linspace(3000.0, 4800.0, int(40 * fs))  # order 2: 100 -> 160 Hz in 40 s
    sig = synth_runup(fs, rpm, [dict(order=2.0, amplitude=0.8, phase=0.7)], seed=1)
    modes = [dict(freq=150.0, zeta=0.05, gain=1.0)]
    y, _ = modal_path(sig.x, fs, modes)
    h = modal_response(sig.order_frequency[:, 0], modes)
    expected = sig.order_amplitude[:, 0] * np.abs(h) * np.cos(sig.order_phase[:, 0] + np.angle(h))
    sel = slice(int(3 * fs), None)
    peak = 0.8 / (2 * 0.05)
    assert np.max(np.abs(y - expected)[sel]) < 0.03 * peak
    assert np.max(np.abs(y)) == pytest.approx(peak, rel=0.03)


def test_modal_path_is_linear_and_scales_with_gain():
    rng = np.random.default_rng(0)
    x1, x2 = rng.standard_normal((2, 6000))
    a, b = 1.7, -0.6
    y12 = modal_path(a * x1 + b * x2, FS, MODES)[0]
    y1, y2 = modal_path(x1, FS, MODES)[0], modal_path(x2, FS, MODES)[0]
    assert y12 == pytest.approx(a * y1 + b * y2, rel=1e-10, abs=1e-12 * np.max(np.abs(y12)))
    assert modal_path(x1, FS, MODES, gain=-2.5)[0] == pytest.approx(-2.5 * y1, rel=1e-12)
    # a negative modal gain is a mode of opposite sign
    neg = modal_path(x1, FS, [dict(freq=300.0, zeta=0.02, gain=-1.0)])[0]
    pos = modal_path(x1, FS, [dict(freq=300.0, zeta=0.02, gain=1.0)])[0]
    assert neg == pytest.approx(-pos, rel=1e-12)
    # zero initial state: the path has relative degree two, so y[0] = 0
    assert y1[0] == 0.0


