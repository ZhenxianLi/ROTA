def test_quantisation_step_error_and_range():
    bits, full = 8, 1.0
    step = 2 * full / 2**bits
    t = np.arange(200000) / FS
    x = 0.9 * np.sin(TWO_PI * 123.456 * t) * np.cos(TWO_PI * 0.7 * t)
    out = measurement_chain(x, FS, bits=bits, full_scale=full)
    y = out["x"]
    codes = y / step
    assert codes == pytest.approx(np.round(codes), abs=1e-9)  # integer multiples of the step
    assert codes.min() >= -2 ** (bits - 1) and codes.max() <= 2 ** (bits - 1) - 1
    assert out["config"]["step"] == pytest.approx([step])
    err = y - x
    assert np.max(np.abs(err)) <= 0.5 * step * (1 + 1e-9)
    assert np.sqrt(np.mean(err**2)) == pytest.approx(step / np.sqrt(12.0), rel=0.02)
    assert abs(np.mean(err)) < 0.02 * step
    assert not out["clipped"].any()
    # fewer bits: coarser step
    y4 = measurement_chain(x, FS, bits=4, full_scale=full)["x"]
    assert np.sqrt(np.mean((y4 - x) ** 2)) == pytest.approx(2 / 16 / np.sqrt(12.0), rel=0.03)
    # saturation of the two's-complement range: +full_scale - step and -full_scale
    sat = measurement_chain(np.array([5.0, -5.0, 0.0]), FS, bits=bits, full_scale=full)
    assert sat["x"] == pytest.approx([full - step, -full, 0.0])
    assert sat["clipped"].tolist() == [True, True, False]
    # full scale in physical units
    out = measurement_chain(np.array([0.3]), FS, bits=12, full_scale=10.0)
    assert out["x"][0] == pytest.approx(0.3, abs=10.0 / 2**12)


