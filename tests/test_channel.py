    f = np.fft.rfftfreq(stem.size, 1 / fs)
    low = np.mean(spec[(f > 200) & (f < 1500)])
    high = np.mean(spec[(f > 5000) & (f < 7500)])
    assert abs(_db(high / low)) < 1.5


