"""Tests of rota_order._channel: transfer paths, background noise and the measurement chain.

Ground truth is analytic or generated by rota_order.synth:

* modal_path against the closed-form modal response (steady-state sine
  amplitude and phase), the sampled analog impulse response, the ring-down
  time constant 1/(zeta w) and the truth of a rota_order.synth run-up order crossing
  the mode slowly (quasi-static) and quickly (dynamic);
* room_impulse_response against the reverberation time recovered by Schroeder
  backward integration;
* speed_noise against the Welch PSD tilt, the RMS level and the level-versus-
  speed law it was given, and against pumping at the grain rate;
* transient_events against the analytic waveform and its timing;
* measurement_chain against clipping, quantisation (error RMS step/sqrt(12)),
  self-noise, DC and the apparent frequency of a tone under clock drift;
* delay_signal against the analytic delayed tone and a cross-spectral delay
  estimate.
"""

