    # many short clicks: flat spectrum (equal energy at low and high frequencies)
    events = [dict(time=0.05 + 0.1 * k, kind="click", amplitude=1.0, decay=0.002) for k in range(60)]
    stem, _ = transient_events(fs, 16000 * 7, events, seed=4)
