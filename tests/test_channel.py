FS = 16000.0
TWO_PI = 2.0 * np.pi
MODES = [dict(freq=300.0, zeta=0.02), dict(freq=1100.0, q=40.0, gain=0.5)]


def _json_roundtrip(cfg):
    """The config survives strict JSON unchanged."""
    assert json.loads(json.dumps(cfg, allow_nan=False)) == cfg


def _fit_tone(y, f, t):
    """Complex amplitude z of y ~ Re(z exp(j 2 pi f t)) by least squares."""
    a = np.column_stack([np.cos(TWO_PI * f * t), -np.sin(TWO_PI * f * t)])
    c = np.linalg.lstsq(a, y, rcond=None)[0]
    return c[0] + 1j * c[1]


def _tone_frequency(y, fs):
    """Frequency in Hz from the slope of the analytic-signal phase over the central 80 %."""
    phase = np.unwrap(np.angle(signal.hilbert(y)))
    k = np.arange(y.size)
    sel = slice(y.size // 10, y.size - y.size // 10)
    return np.polyfit(k[sel], phase[sel], 1)[0] * fs / TWO_PI


def _db(x):
    return 10.0 * np.log10(x)


