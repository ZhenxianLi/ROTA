def _welch_tilt(y, lo=100.0, hi=6000.0):
    """Slope in dB per octave of the Welch PSD between ``lo`` and ``hi`` Hz."""
    f, p = signal.welch(y, FS, nperseg=4096)
    sel = (f >= lo) & (f <= hi)
    return np.polyfit(np.log2(f[sel]), _db(p[sel]), 1)[0]


