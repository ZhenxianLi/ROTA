def _schroeder_rt60(h, fs, lo=-5.0, hi=-35.0):
    """Reverberation time from the Schroeder energy decay curve (T30, extrapolated to 60 dB)."""
    edc = np.cumsum(h[::-1] ** 2)[::-1]
    db = _db(edc / edc[0])
    i1, i2 = np.argmax(db <= lo), np.argmax(db <= hi)
    slope = np.polyfit(np.arange(i1, i2) / fs, db[i1:i2], 1)[0]
    return -60.0 / slope


@pytest.mark.parametrize("rt60", [0.25, 0.8])
def test_reverberation_time_from_schroeder_integration(rt60):
    rts = []
    for seed in range(4):
        h, _ = room_impulse_response(FS, rt60, n_channels=2, direct_delay=0.003, seed=seed)
        rts += [_schroeder_rt60(h[:, c], FS) for c in range(2)]
    assert np.max(np.abs(np.array(rts) / rt60 - 1)) < 0.05, rts  # measured below 3 %
    assert np.mean(rts) == pytest.approx(rt60, rel=0.02)
    # the T20 range gives the same time (the decay is exponential, not only on average)
    h, _ = room_impulse_response(FS, rt60, length=int(2 * rt60 * FS), seed=9)
    assert _schroeder_rt60(h, FS, -5.0, -25.0) == pytest.approx(rt60, rel=0.08)  # one realisation: up to 5 %


def test_amplitude_envelope_falls_by_60_db_in_rt60():
    rt60 = 0.6
    h, cfg = room_impulse_response(FS, rt60, seed=2)
    assert cfg["amplitude_decay_time"] == pytest.approx(rt60 / np.log(1000.0), rel=1e-12)
    # the mean energy of successive 20 ms blocks follows exp(-2 t / tau_a), whose slope
    # is -60 dB per rt60 over the whole 90 dB of the response (40 realisations)
    block = int(0.02 * FS)
    energy = np.zeros(h.size // block)
    for seed in range(40):
        hh, _ = room_impulse_response(FS, rt60, length=h.size, seed=100 + seed)
        energy += (hh[: energy.size * block] ** 2).reshape(-1, block).sum(axis=1)
    slope = np.polyfit((np.arange(energy.size) + 0.5) * 0.02, _db(energy), 1)[0]
    assert -60.0 / slope == pytest.approx(rt60, rel=0.01)  # measured within 0.05 %


def test_impulse_response_has_unit_energy_in_every_channel():
    h, _ = room_impulse_response(FS, 0.5, n_channels=3, interchannel_delay=0.001, seed=3)
    assert np.sum(h**2, axis=0) == pytest.approx(np.ones(3), rel=1e-12)
    short, _ = room_impulse_response(FS, 0.5, length=2000, seed=3)  # truncated tail: still unit energy
    assert short.shape == (2000,)
    assert np.sum(short**2) == pytest.approx(1.0, rel=1e-12)
    # a white input keeps its power on average
    rng = np.random.default_rng(0)
    x = rng.standard_normal(200000)
    y = apply_ir(x, h[:, 0])
    assert np.mean(y[len(h):] ** 2) == pytest.approx(1.0, rel=0.08)


def test_channel_delays_move_the_onset_of_each_channel():
    d0, dc = 0.0123, 0.00071  # fractional delays in samples
    h, cfg = room_impulse_response(FS, 0.4, n_channels=3, direct_delay=d0, interchannel_delay=dc, seed=4)
    assert h.shape[1] == 3
    expected = [math.ceil((d0 + c * dc) * FS - 1e-9) for c in range(3)]
    first = [int(np.argmax(h[:, c] != 0.0)) for c in range(3)]
    assert first == expected
    assert cfg["onset_samples"] == expected
    assert cfg["delays"] == pytest.approx([d0, d0 + dc, d0 + 2 * dc])
    # a vector gives the extra delay of each channel; a negative step makes later channels earlier
    h2, cfg2 = room_impulse_response(FS, 0.4, n_channels=2, direct_delay=0.01, interchannel_delay=[0.0, -0.004], seed=4)
    assert [int(np.argmax(h2[:, c] != 0.0)) for c in range(2)] == [160, 96]
    assert cfg2["delays"] == pytest.approx([0.01, 0.006])
    # default length: 1.5 reverberation times after the latest onset
    assert h.shape[0] == math.ceil(FS * (d0 + 2 * dc + 1.5 * 0.4))
    # a delay of exactly one sample places the first non-zero sample at index 1 with full envelope
    h3, _ = room_impulse_response(FS, 0.4, direct_delay=1.0 / FS, seed=4)
    assert np.argmax(h3 != 0.0) == 1


def test_room_channels_are_independent_realisations():
    h, _ = room_impulse_response(FS, 0.5, n_channels=2, seed=5)
    rho = np.corrcoef(h[:, 0], h[:, 1])[0, 1]
    assert abs(rho) < 0.2  # std of the estimate is about 0.03
    # channel c does not depend on the number of channels
    a, _ = room_impulse_response(FS, 0.5, length=5000, n_channels=1, seed=5)
    b, _ = room_impulse_response(FS, 0.5, length=5000, n_channels=3, seed=5)
    assert b[:, 0] == pytest.approx(a, rel=1e-14)
    assert not np.allclose(b[:, 0], b[:, 1])


def test_room_impulse_response_is_reproducible_and_records_its_seed():
    a, ca = room_impulse_response(FS, 0.3, n_channels=2, seed=11)
    b, _ = room_impulse_response(FS, 0.3, n_channels=2, seed=11)
    c, _ = room_impulse_response(FS, 0.3, n_channels=2, seed=12)
    assert np.array_equal(a, b)
    assert not np.array_equal(a, c)
    assert ca["seed"] == 11
    _json_roundtrip(ca)
    d, cd = room_impulse_response(FS, 0.3, n_channels=2, seed=None)  # fresh entropy ...
    e, _ = room_impulse_response(FS, 0.3, n_channels=2, seed=cd["seed"])  # ... rebuilt from the record
    assert np.array_equal(d, e)
    g, cg = room_impulse_response(FS, 0.3, seed=np.random.default_rng(1))
    assert cg["seed"] is None
    assert g.ndim == 1


