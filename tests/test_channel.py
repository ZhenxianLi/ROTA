def _band_limited_noise(n, seed, edge=0.2):
    """Gaussian noise limited to ``edge`` * fs (zero-phase FIR, so no start-up delay)."""
    rng = np.random.default_rng(seed)
    taps = signal.firwin(255, 2 * edge)
    return signal.fftconvolve(rng.standard_normal(n + 400), taps, mode="same")[200:200 + n]


def _delay_estimate(x, y, fs, fmax):
    """Delay in samples from the phase slope of the cross spectrum (weighted least squares)."""
    spec_x, spec_y = np.fft.rfft(x), np.fft.rfft(y)
    f = np.fft.rfftfreq(x.size, 1 / fs)
    sel = (f > 100.0) & (f < fmax)
    w = np.abs(spec_x[sel]) ** 2
    phase = np.unwrap(np.angle(spec_y[sel] / spec_x[sel]))
    slope = np.sum(w * phase * f[sel]) / np.sum(w * f[sel] ** 2)  # phase = -2 pi f delay
    return -slope / TWO_PI * fs


@pytest.mark.parametrize("delay_samples", [3.37, -2.5, 0.001, 17.9])
def test_fractional_delay_of_band_limited_noise_to_1e_3_samples(delay_samples):
    x = _band_limited_noise(40000, seed=1)
    y = delay_signal(x, FS, delay_samples / FS)
    assert _delay_estimate(x, y, FS, 0.18 * FS) == pytest.approx(delay_samples, abs=1e-3)


@pytest.mark.parametrize("f_rel", [0.01, 0.1, 0.25, 0.4, 0.45])
def test_fractional_delay_of_a_tone_matches_the_analytic_delayed_tone(f_rel):
    n, d = 4000, 6.37  # samples
    k = np.arange(n)
    x = np.cos(TWO_PI * f_rel * k + 0.9)
