def test_thump_is_the_analytic_damped_burst_at_its_time():
    fs, t0, amp, decay, freq = 16000.0, 0.1234567, 2.0, 0.05, 25.0
    stem, cfg = transient_events(fs, 16000, [dict(time=t0, kind="thump", amplitude=amp, decay=decay, freq=freq)])
    w = TWO_PI * freq
    tau_peak = np.arctan(w * decay) / w
    scale = np.exp(-tau_peak / decay) * np.sin(w * tau_peak)
    i0 = math.ceil(t0 * fs)
    tau = np.arange(i0, 16000) / fs - t0
    expected = amp / scale * np.exp(-tau / decay) * np.sin(w * tau)
    assert stem[i0:] == pytest.approx(expected, rel=1e-12, abs=1e-14)
    assert np.all(stem[:i0] == 0.0)  # nothing before the onset
    assert stem[i0] != 0.0  # fractional time: the first sample at or after t0 is the onset
    ev = cfg["events"][0]
    assert ev["onset_sample"] == i0
    # peak amplitude (to the sampling of the continuous peak) and its time
    assert np.max(np.abs(stem)) == pytest.approx(amp, rel=2e-4)
    assert ev["peak_sample"] == int(np.argmax(np.abs(stem)))
    assert ev["peak_time"] == pytest.approx(t0 + tau_peak, abs=1.0 / fs)
    assert ev["n_samples"] == 16000 - i0
    _json_roundtrip(cfg)


