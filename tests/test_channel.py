def test_integer_and_zero_delays_are_exact_shifts():
    rng = np.random.default_rng(4)
    x = rng.standard_normal(500)
    assert np.array_equal(delay_signal(x, FS, 0.0), x)
    y = delay_signal(x, FS, 7.0 / FS)
    assert y[7:] == pytest.approx(x[:-7], abs=1e-12)
    assert np.all(np.abs(y[:7]) < 1e-12)
    z = delay_signal(x, FS, -4.0 / FS)  # an advance
    assert z[:-4] == pytest.approx(x[4:], abs=1e-12)
    assert np.all(np.abs(z[-4:]) < 1e-12)
    # a delay longer than the record leaves silence
    assert np.all(delay_signal(x, FS, 1.0) == 0.0)
    assert np.all(delay_signal(x, FS, -1.0) == 0.0)


def test_delay_signal_composes_inverts_and_preserves_dc():
    x = _band_limited_noise(6000, seed=2)
    a, b = 2.3 / FS, 4.45 / FS
    ab = delay_signal(delay_signal(x, FS, a), FS, b)
    direct = delay_signal(x, FS, a + b)
    assert np.max(np.abs(ab - direct)[200:-200]) < 1e-4 * np.max(np.abs(x))
    back = delay_signal(delay_signal(x, FS, a), FS, -a)
    assert np.max(np.abs(back - x)[200:-200]) < 1e-4 * np.max(np.abs(x))
    c = delay_signal(np.full(2000, 5.0), FS, 3.3 / FS)
    assert c[100:-100] == pytest.approx(5.0, abs=1e-12)


def test_delay_signal_multichannel_and_validation():
    rng = np.random.default_rng(5)
    x = rng.standard_normal((300, 3))
    same = delay_signal(x, FS, 2.5 / FS)
    assert same.shape == x.shape
    for c in range(3):
        assert same[:, c] == pytest.approx(delay_signal(x[:, c], FS, 2.5 / FS), abs=1e-14)
    per = delay_signal(x, FS, np.array([0.0, 3.0, -1.5]) / FS)
    assert per[:, 0] == pytest.approx(x[:, 0], abs=1e-14)
    assert per[3:, 1] == pytest.approx(x[:-3, 1], abs=1e-12)
    assert per[:, 2] == pytest.approx(delay_signal(x[:, 2], FS, -1.5 / FS), abs=1e-14)
    assert delay_signal(x[:, 0], FS, 1e-4).shape == (300,)
    with pytest.raises(ValueError):
        delay_signal(x, FS, [1e-3, 2e-3])
    with pytest.raises(ValueError):
        delay_signal(x, FS, float("nan"))
    with pytest.raises(ValueError):
        delay_signal(x, 0.0, 1e-3)


def test_tacho_misalignment_workflow():
    # A synth_runup tachometer delayed by a fractional number of samples against
    # the audio: the 50 % crossings of the pulses move by exactly the delay.
    fs = 8000.0
    rpm = np.full(int(2 * fs), 1500.0)
    sig = synth_runup(fs, rpm, [dict(order=1.0)], tacho_ppr=1, seed=1)
    delay = 0.00123  # 9.84 samples
    late = delay_signal(sig.tacho, fs, delay)
    level = 0.5 * np.max(sig.tacho)

    def edges(v):
        i = np.flatnonzero((v[:-1] < level) & (v[1:] >= level))
        return (i + (level - v[i]) / (v[i + 1] - v[i])) / fs

    e0, e1 = edges(sig.tacho), edges(late)
    assert e0.size == e1.size > 10
    # the interpolation overshoots slightly at the pulse edges, which moves the
    # crossing by a small fraction of a sample at most
    assert np.max(np.abs(e1 - e0 - delay)) < 0.05 / fs
