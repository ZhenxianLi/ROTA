def test_click_has_the_stated_peak_decay_and_a_broadband_spectrum():
    fs = 16000.0
    stem, cfg = transient_events(fs, 32000, [dict(time=0.25, kind="click", amplitude=-1.5, decay=0.2)], seed=3)
    ev = cfg["events"][0]
    assert np.max(np.abs(stem)) == pytest.approx(1.5, rel=1e-12)  # exactly the stated peak ...
    assert stem[ev["peak_sample"]] < 0.0  # ... of the stated sign
    assert np.all(stem[: ev["onset_sample"]] == 0.0)
    assert ev["onset_sample"] == 4000
    assert stem[4000] != 0.0
    # exponential decay: the power in 20 ms blocks falls by 2 / decay, 8.69 dB per decay time,
    # over four decay times (measured within 1.2 % over 40 seeds)
    blocks = _db(np.mean(stem[4000:4000 + 40 * 320].reshape(40, 320) ** 2, axis=1))
    slope = np.polyfit((np.arange(40) + 0.5) * 0.02, blocks, 1)[0]
